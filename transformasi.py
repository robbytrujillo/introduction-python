# Mengubah Huruf Besar/Kecil
# upper
kata = 'dicoding'
kata = kata.upper()
print(kata)

"""
Output:
DICODING
"""

# lower
kata = 'DICODING'
kata = kata.lower()
print(kata)

"""
Output:
dicoding
"""

# Awalan dan Akhiran
# rstrip()
print("Dicoding".rstrip() + " Indonesia")

"""
Output:
Dicoding Indonesia
"""

# lstrip()
print("           Dicoding".lstrip())

"""
Output:
Dicoding
"""